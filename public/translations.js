function getPreferredLanguage() {
    const saved = localStorage.getItem('recol_lang');
    if (saved && TRANSLATIONS[saved]) return saved;
    const browserLang = (navigator.language || 'en').slice(0, 2).toLowerCase();
    return TRANSLATIONS[browserLang] ? browserLang : 'en';
}

function applyTranslations(lang) {
    if (!TRANSLATIONS[lang]) lang = 'en';
    const dict = TRANSLATIONS[lang];

    document.documentElement.lang = lang;

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) el.textContent = dict[key];
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (dict[key]) el.placeholder = dict[key];
    });

    document.querySelectorAll('.lang-select').forEach(sel => { sel.value = lang; });

    localStorage.setItem('recol_lang', lang);
    window.RECOL_LANG = lang;
}

document.addEventListener('DOMContentLoaded', () => {
    applyTranslations(getPreferredLanguage());
    document.querySelectorAll('.lang-select').forEach(sel => {
        sel.addEventListener('change', (e) => applyTranslations(e.target.value));
    });
});